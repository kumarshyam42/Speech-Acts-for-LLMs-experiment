#!/usr/bin/env python3
"""
h2 — B1n scorer (rules-equipped arm). Same mechanical stage and hand-pass merge
as score_b1.py (whose TRAP_TERMS map and boundary matcher it imports), plus the
paired B1<->B1n comparison the locked rubric-b1n.md requires. The kill bars are
applied on the FINAL hand-adjudicated calls (out/veto_adjudication_b1n.json),
mirrored from the documented reasoning in out/veto_flag_adjudication.md.

Reads verdicts-b1n/verdicts.json + out/veto_readability.csv (B1 pairing).
Writes out/veto_readability_b1n.csv + out/veto_readability_b1n_summary.md.
Stdlib Py3.9, idempotent.
"""

import csv
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import importlib.util
_spec = importlib.util.spec_from_file_location(
    "score_b1", os.path.join(HERE, "score_b1.py"))
sb1 = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(sb1)  # TRAP_TERMS, mentions, CSV_COLUMNS

VERDICTS = os.path.join(HERE, "verdicts-b1n", "verdicts.json")
OUT_DIR = os.path.join(HERE, "out")
ADJUDICATION = os.path.join(OUT_DIR, "veto_adjudication_b1n.json")
B1_CSV = os.path.join(OUT_DIR, "veto_readability.csv")
REPS = ["rep1", "rep2", "rep3"]


def main():
    with open(VERDICTS, encoding="utf-8") as f:
        records = json.load(f)["verdicts"]
    ok = [r for r in records if r["status"] == "ok"]
    errs = [r for r in records if r["status"] != "ok"]

    adjudication = {}
    if os.path.exists(ADJUDICATION):
        with open(ADJUDICATION, encoding="utf-8") as f:
            adjudication = {k: v for k, v in json.load(f).items()
                            if not k.startswith("_")}

    rows = []
    for r in sorted(ok, key=lambda x: (x["rep"], x["task"])):
        v = r["verdict"]
        flags_text = " || ".join(
            "%s [span: %s]" % (fl["description"], fl["span"])
            for fl in v["risk_flags"])
        mech, terms = "", []
        if r["class"] == "4":
            tl = flags_text.lower()
            terms = [t for t in sb1.TRAP_TERMS.get(r["task"], [])
                     if sb1.mentions(tl, t)]
            mech = bool(terms)
        adj = adjudication.get(r["label"], {})
        rows.append({
            "label": r["label"], "rep": r["rep"], "task": r["task"],
            "class": r["class"], "accept": v["accept"],
            "n_flags": len(v["risk_flags"]),
            "mech_trap_match": mech, "matched_terms": ";".join(terms),
            "trap_flagged_final": adj.get("trap_flagged", ""),
            "misread_flagged_final": adj.get("misread_flagged", ""),
            "control_trap_false_alarm": adj.get("control_trap_false_alarm", ""),
            "adjudication_note": adj.get("note", ""),
            "primary_risk": v.get("primary_risk", ""),
            "flags_concat": flags_text,
        })

    os.makedirs(OUT_DIR, exist_ok=True)
    with open(os.path.join(OUT_DIR, "veto_readability_b1n.csv"), "w",
              encoding="utf-8", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(sb1.CSV_COLUMNS)
        for row in rows:
            w.writerow([str(row[c]) for c in sb1.CSV_COLUMNS])

    # B1 pairing (contract-only arm), keyed by label.
    b1_rows = {}
    if os.path.exists(B1_CSV):
        with open(B1_CSV, newline="", encoding="utf-8") as f:
            for r in csv.DictReader(f):
                b1_rows[r["label"]] = r

    L = []
    L.append("# h2 B1n (rules-equipped) veto-readability — summary + paired comparison")
    L.append("")
    L.append("*Generated by `score_b1n.py` under the LOCKED `../rubric-b1n.md` (commissioned "
             "by Shyam 260706). EXPLORATORY — P2 arm (c) run on the generating corpus. "
             "B1 (contract-only) is the ablation; this arm gives the reviewer "
             "docs/requirements.md + CONTRIBUTING.md. Same episodes, labels, bars, and "
             "hand-pass discipline as B1; final calls in `veto_adjudication_b1n.json`, "
             "reasoning appended to `veto_flag_adjudication.md`.*")
    L.append("")
    L.append("- Episodes judged: %d ok / %d judge_error" % (len(ok), len(errs)))
    L.append("")
    L.append("## Accept-rates per class")
    L.append("")
    L.append("| Class | n | yes | yes_with_conditions | no | mean flags |")
    L.append("|---|---|---|---|---|---|")
    for klass in ("1", "2", "3", "4"):
        sub = [r for r in rows if r["class"] == klass]
        if not sub:
            continue
        cnt = {a: sum(1 for r in sub if r["accept"] == a)
               for a in ("yes", "yes_with_conditions", "no")}
        L.append("| %s | %d | %d | %d | %d | %.1f |" % (
            klass, len(sub), cnt["yes"], cnt["yes_with_conditions"], cnt["no"],
            sum(r["n_flags"] for r in sub) / len(sub)))
    L.append("")
    c4 = [r for r in rows if r["class"] == "4"]
    L.append("## Class-4 paired table (B1 contract-only vs B1n with rules)")
    L.append("")
    L.append("| label | rep | task | B1 accept | B1n accept | B1 mech | B1n mech | "
             "B1n FINAL (hand) | note |")
    L.append("|---|---|---|---|---|---|---|---|---|")
    for r in c4:
        b1r = b1_rows.get(r["label"], {})
        L.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            r["label"], r["rep"], r["task"], b1r.get("accept", "?"), r["accept"],
            b1r.get("mech_trap_match", "?"), r["mech_trap_match"],
            r["trap_flagged_final"], r["adjudication_note"]))
    L.append("")
    if adjudication:
        trap_final = [r for r in c4 if r["trap_flagged_final"] is True]
        c2 = [r for r in rows if r["class"] == "2"]
        misread_final = [r for r in c2 if r["misread_flagged_final"] is True]
        c1 = [r for r in rows if r["class"] == "1"]
        fa_final = [r for r in c1 if r["control_trap_false_alarm"] is True]
        c4_no = sum(1 for r in c4 if r["accept"] == "no")
        c1_no = sum(1 for r in c1 if r["accept"] == "no")
        bar1 = len(trap_final) * 3 >= len(c4) * 2
        L.append("## FINAL adjudicated results (B1n)")
        L.append("")
        L.append("- Class-4 trap-flag sensitivity: **%d/%d** (B1 was 3/12)"
                 % (len(trap_final), len(c4)))
        L.append("- Class-2 misread-flag sensitivity: **%d/%d** (B1 was 12/14)"
                 % (len(misread_final), len(c2)))
        L.append("- Controls: trap-level false alarms %d/%d; rejections %d/%d "
                 "(class-4 rejections %d/%d)"
                 % (len(fa_final), len(c1), c1_no, len(c1), c4_no, len(c4)))
        L.append("- **Kill bars (same as B1): %s** — sensitivity %s (%d/%d vs >=8/12)."
                 % ("SUPPORTED" if bar1 else "NOT MET",
                    "met" if bar1 else "FAILED", len(trap_final), len(c4)))
        L.append("")
    else:
        L.append("## Hand-pass worklist")
        L.append("")
        L.append("Adjudicate all class-4/class-2/control rows in "
                 "veto_flag_adjudication.md, mirror into veto_adjudication_b1n.json, "
                 "re-run this scorer.")
        L.append("")
    if errs:
        L.append("## Judge errors (listed, never dropped)")
        L.append("")
        for r in errs:
            L.append("- %s (%s/%s): %s" % (r.get("label"), r.get("rep"),
                                           r.get("task"), r.get("error", "?")))
        L.append("")
    with open(os.path.join(OUT_DIR, "veto_readability_b1n_summary.md"), "w",
              encoding="utf-8", newline="") as f:
        f.write("\n".join(L) + "\n")
    print("Scored %d episodes -> %s" % (len(rows), OUT_DIR))


if __name__ == "__main__":
    main()
