#!/usr/bin/env python3
"""
h8 (typed-decision instability) — WP-A / A3 mechanical census.

Implements EXACTLY the locked definitions in this folder's README.md
("Phase-2 locked definitions (260706)"): the act-per-task-per-rep census, the
flip-task outcome-linkage table (asymmetric by construction: promise reps carry
judge verdicts, non-promise reps carry only terminated-without-execution plus
the FIXED class-appropriate-direction mapping), the operationalized kill
criterion, and the A/B' executed-flip context census.

Reads ONLY the frozen runs/<rep>/merged.csv files. Writes ONLY out/.
Standard library only, Python 3.9, idempotent (byte-identical re-runs).
"""

import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
EXPERIMENT = os.path.dirname(os.path.dirname(HERE))
RUNS_DIR = os.path.join(EXPERIMENT, "runs")
OUT_DIR = os.path.join(HERE, "out")

REPS = ["rep1", "rep2", "rep3"]

# Locked class-level mapping (rubrics/index.md per-class checklists): the
# rubric-correct DIRECTION for a phase-1 act. Class-level, never per-episode.
CLASS_CORRECT_DIRECTION = {
    "1": "promise (non-promise = reflexive-negotiation tax)",
    "2": "surface/propose (non-promise termination is class-appropriate)",
    "3": "decline/redirect (non-promise termination is class-appropriate)",
    "4": "surface conflict (non-promise termination is class-appropriate)",
}


def load():
    """{task: {rep: rowdict}} for B episodes; plus per-condition executed maps."""
    b = {}
    executed = {"A": {}, "Bp": {}}
    classes = {}
    for rep in REPS:
        with open(os.path.join(RUNS_DIR, rep, "merged.csv"),
                  newline="", encoding="utf-8") as f:
            for r in csv.DictReader(f):
                classes[r["task"]] = r["class"]
                if r["condition"] == "B":
                    b.setdefault(r["task"], {})[rep] = r
                elif r["condition"] in executed:
                    executed[r["condition"]].setdefault(r["task"], {})[rep] = \
                        r["executed"]
    return b, executed, classes


def main():
    b, executed, classes = load()
    if len(b) != 24 or any(len(v) != 3 for v in b.values()):
        raise SystemExit("Expected 24 tasks x 3 reps of B episodes")
    os.makedirs(OUT_DIR, exist_ok=True)

    # ---- act_by_task_rep.csv ----
    tasks = sorted(b)
    flip_tasks = [t for t in tasks
                  if len({b[t][rep]["speech_act"] for rep in REPS}) > 1]
    with open(os.path.join(OUT_DIR, "act_by_task_rep.csv"), "w",
              encoding="utf-8", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["task", "class", "rep1_act", "rep2_act", "rep3_act", "flip"])
        for t in tasks:
            w.writerow([t, classes[t]] + [b[t][rep]["speech_act"] for rep in REPS]
                       + [t in flip_tasks])

    # ---- flip_outcomes.csv ----
    flip_cols = ["task", "class", "rep", "speech_act", "executed", "job3_outcome",
                 "job3_gradient", "judged_failure", "job2_localization",
                 "termination_note"]
    flip_rows = []
    for t in flip_tasks:
        for rep in REPS:
            r = b[t][rep]
            is_promise = r["speech_act"] == "promise"
            if is_promise:
                note = ""
            else:
                note = ("terminated-without-execution; class direction: %s"
                        % CLASS_CORRECT_DIRECTION[classes[t]])
            flip_rows.append({
                "task": t, "class": classes[t], "rep": rep,
                "speech_act": r["speech_act"], "executed": r["executed"],
                "job3_outcome": r["job3_outcome"] if is_promise else "",
                "job3_gradient": r["job3_gradient"] if is_promise else "",
                "judged_failure": r["judged_failure"] if is_promise else "",
                "job2_localization": r["job2_localization"] if is_promise else "",
                "termination_note": note,
            })
    with open(os.path.join(OUT_DIR, "flip_outcomes.csv"), "w",
              encoding="utf-8", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(flip_cols)
        for row in flip_rows:
            w.writerow([str(row[c]) for c in flip_cols])

    # ---- context: A / B' executed flips ----
    exec_flips = {}
    for cond in ("A", "Bp"):
        exec_flips[cond] = sorted(
            t for t in tasks
            if len({executed[cond][t][rep] for rep in REPS}) > 1)

    # ---- summary + kill check ----
    L = []
    L.append("# h8 act-stability census — summary (WP-A / A3)")
    L.append("")
    L.append("*Generated by `act_stability.py` under the locked definitions in "
             "`../README.md` (260706). EXPLORATORY, descriptive only; N=3 reps — "
             "direction only. Non-promise B episodes have NO judged outcome (Job 3 "
             "never ran on terminated episodes); the linkage below never pretends "
             "otherwise.*")
    L.append("")
    L.append("- Flip tasks (B act differs across reps): %d/24 — %s"
             % (len(flip_tasks), ", ".join(flip_tasks)))
    L.append("- A executed-flip tasks (same instability, no typed surface): %s"
             % (", ".join(exec_flips["A"]) or "none"))
    L.append("- B' executed-flip tasks: %s" % (", ".join(exec_flips["Bp"]) or "none"))
    L.append("")
    L.append("## Flip-task linkage (promise reps judged; non-promise reps terminate)")
    L.append("")
    L.append("| Task | Class | Acts (r1/r2/r3) | Promise-rep verdicts | Non-promise reps |")
    L.append("|---|---|---|---|---|")
    uniform_fail = []
    counterexamples = []
    for t in flip_tasks:
        acts = [b[t][rep]["speech_act"] for rep in REPS]
        promise_verdicts = []
        n_nonpromise = 0
        for rep in REPS:
            r = b[t][rep]
            if r["speech_act"] == "promise":
                promise_verdicts.append("%s: %s/%s" % (
                    rep, r["job3_outcome"] or "-", r["job3_gradient"] or "-"))
            else:
                n_nonpromise += 1
        # Kill-criterion tallies are scoped to classes 2-4 (same population as
        # the denominator below) — a class-1 flip would be reported in the table
        # but never counted toward the criterion. Both locked conditions are
        # required: uniform promise-rep failure AND every non-promise rep being
        # a class-appropriate termination (for classes 2-4 the locked mapping
        # deems termination-without-execution class-appropriate; `executed`
        # is checked so the condition is enforced, not assumed).
        if classes[t] in ("2", "3", "4"):
            outcomes = {b[t][rep]["job3_outcome"] for rep in REPS
                        if b[t][rep]["speech_act"] == "promise"}
            nonpromise_ok = all(
                b[t][rep]["executed"] != "True"
                for rep in REPS if b[t][rep]["speech_act"] != "promise")
            if outcomes == {"fail"} and nonpromise_ok:
                uniform_fail.append(t)
            elif "pass" in outcomes:
                counterexamples.append(t)
        L.append("| %s | %s | %s | %s | %d terminated pre-execution |" % (
            t, classes[t], "/".join(a.replace("counter_offer", "CO") for a in acts),
            "; ".join(promise_verdicts), n_nonpromise))
    L.append("")
    flips_24 = [t for t in flip_tasks if classes[t] in ("2", "3", "4")]
    L.append("## Kill-criterion check (locked)")
    L.append("")
    L.append("Strong claim survives iff >=half of flip tasks in classes 2-4 show "
             "uniform promise-rep failure with class-appropriate non-promise "
             "terminations; else downgrade to \"acts are unstable\" only.")
    L.append("")
    L.append("- Flip tasks in classes 2-4: %d (%s)" % (len(flips_24), ", ".join(flips_24)))
    L.append("- With uniform promise-rep FAIL: %d (%s)"
             % (len(uniform_fail), ", ".join(uniform_fail) or "none"))
    L.append("- Counterexamples (a promise rep passed): %s"
             % (", ".join(counterexamples) or "none"))
    half = len(uniform_fail) * 2 >= len(flips_24) and len(flips_24) > 0
    L.append("")
    L.append("**Kill-criterion result: %s** (%d/%d flip tasks show uniform "
             "promise-rep failure)." % (
                 "STRONG CLAIM SURVIVES" if half else
                 "DOWNGRADE to 'acts are unstable'",
                 len(uniform_fail), len(flips_24)))
    L.append("")
    L.append("All flip-task non-promise episodes terminated pre-execution; per the "
             "locked class mapping, that is the class-appropriate direction for "
             "classes 2-4 (it is a per-CLASS rubric fact, not a per-episode judgment).")
    L.append("")
    with open(os.path.join(OUT_DIR, "act_stability_summary.md"), "w",
              encoding="utf-8", newline="") as f:
        f.write("\n".join(L) + "\n")
    print("Wrote act_by_task_rep.csv (%d tasks), flip_outcomes.csv (%d rows), "
          "summary to %s" % (len(tasks), len(flip_rows), OUT_DIR))


if __name__ == "__main__":
    main()
