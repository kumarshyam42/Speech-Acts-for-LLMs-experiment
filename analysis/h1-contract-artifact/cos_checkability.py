#!/usr/bin/env python3
"""
h1 (contract artifact) — WP-A / A2, part 2: CoS checkability census.

Implements EXACTLY the locked decision list in this folder's README.md
("Phase-2 locked definitions (260706)"): a declared CoS is OBSERVABLE if any
of the FILE / TEST / EXIT / QUOTE / FLAG / NUM rules hit, else VAGUE.
Also emits the deterministic 30-CoS spot-check sample (seed 260706) that gets
hand-labeled in out/cos_spotcheck.md — the sample is selected here so it is
reproducible, but the hand labels never feed back into this scorer.

Reads ONLY frozen artifacts: runs/<rep>/merged.csv + negotiation.json.
Writes ONLY out/cos_checkability.csv and out/cos_checkability_summary.md.

Standard library only, Python 3.9, idempotent (byte-identical re-runs).
"""

import csv
import json
import os
import random
import re

HERE = os.path.dirname(os.path.abspath(__file__))
EXPERIMENT = os.path.dirname(os.path.dirname(HERE))
RUNS_DIR = os.path.join(EXPERIMENT, "runs")
OUT_DIR = os.path.join(HERE, "out")

REPS = ["rep1", "rep2", "rep3"]

RULES = [
    ("FILE", re.compile(
        r"[A-Za-z0-9_./-]*[A-Za-z0-9_-]+\.(?:py|md|txt|json|toml|cfg|ini|csv)\b")),
    ("TEST", re.compile(
        r"\btest_[a-z0-9_]+\b|\bpytest\b|\btest suite\b|\bsuite passes\b|\btests pass\b",
        re.IGNORECASE)),
    ("EXIT", re.compile(
        r"\bexit code\b|\bexit status\b|\bexit(?:s)?(?: code| status)? \d\b"
        r"|\bnon-?zero exit\b", re.IGNORECASE)),
    ("QUOTE", re.compile(r"`[^`]{3,}`|\"[^\"]{3,}\"")),
    ("FLAG", re.compile(r"(?<![\w-])--[a-z][a-z0-9-]+\b")),
    ("NUM", re.compile(
        r"==|>=|<=|\bat least \d|\bat most \d|\b\d+(?:\.\d+)?%")),
]

CSV_COLUMNS = ["rep", "task", "class", "speech_act", "cos_index", "verdict",
               "rules_hit", "spotcheck_sample", "cos_text"]


def classify(text):
    hits = [name for name, rx in RULES if rx.search(text)]
    return ("observable" if hits else "vague"), hits


def main():
    rows = []
    for rep in REPS:
        with open(os.path.join(RUNS_DIR, rep, "merged.csv"),
                  newline="", encoding="utf-8") as f:
            b_rows = [r for r in csv.DictReader(f) if r["condition"] == "B"]
        b_rows.sort(key=lambda r: r["task"])
        for r in b_rows:
            ep_dir = os.path.join(RUNS_DIR, rep, "%s-B" % r["task"])
            with open(os.path.join(ep_dir, "negotiation.json"),
                      encoding="utf-8") as f:
                neg = json.load(f)
            cos_list = (neg.get("parsed") or {}).get("conditions_of_satisfaction") or []
            cos_list = [c for c in cos_list if isinstance(c, str)]
            for i, cos in enumerate(cos_list):
                verdict, hits = classify(cos)
                rows.append({
                    "rep": rep, "task": r["task"], "class": r["class"],
                    "speech_act": r["speech_act"], "cos_index": i,
                    "verdict": verdict, "rules_hit": "+".join(hits),
                    "spotcheck_sample": False, "cos_text": cos,
                })

    # Deterministic spot-check sample (seed = 260706, locked in README).
    sample_idx = sorted(random.Random(260706).sample(range(len(rows)), 30))
    for idx in sample_idx:
        rows[idx]["spotcheck_sample"] = True

    os.makedirs(OUT_DIR, exist_ok=True)
    with open(os.path.join(OUT_DIR, "cos_checkability.csv"), "w",
              encoding="utf-8", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(CSV_COLUMNS)
        for row in rows:
            w.writerow([str(row[c]) for c in CSV_COLUMNS])

    # ---- summary ----
    def share(sub):
        obs = sum(1 for r in sub if r["verdict"] == "observable")
        return "%d/%d (%.0f%%)" % (obs, len(sub), 100.0 * obs / len(sub)) \
            if sub else "-"

    L = []
    L.append("# h1 CoS checkability census — summary (WP-A / A2)")
    L.append("")
    L.append("*Generated by `cos_checkability.py` under the locked decision list in "
             "`../README.md` (260706). EXPLORATORY, descriptive only. Heuristic "
             "verdicts; error bounded by the 30-CoS hand spot-check in "
             "`cos_spotcheck.md`, which never overwrites the census.*")
    L.append("")
    L.append("- Total declared CoS: %d across %d B episodes" % (
        len(rows), len({(r["rep"], r["task"]) for r in rows})))
    promise_rows = [r for r in rows if r["speech_act"] == "promise"]
    L.append("- Observable share, ALL CoS: %s" % share(rows))
    L.append("- Observable share, PROMISE CoS (kill-criterion population): %s"
             % share(promise_rows))
    L.append("- Kill threshold (locked): <50% observable among promise CoS = "
             "\"mostly vague\"; 50-70% = caveat.")
    L.append("")
    L.append("## Per class x speech_act (pooled reps)")
    L.append("")
    L.append("| Class | promise | counter_offer | decline |")
    L.append("|---|---|---|---|")
    for klass in ("1", "2", "3", "4"):
        cells = []
        for act in ("promise", "counter_offer", "decline"):
            sub = [r for r in rows if r["class"] == klass and r["speech_act"] == act]
            cells.append(share(sub))
        L.append("| %s | %s |" % (klass, " | ".join(cells)))
    L.append("")
    L.append("## Per rep (promise CoS)")
    L.append("")
    L.append("| Rep | observable share |")
    L.append("|---|---|")
    for rep in REPS:
        L.append("| %s | %s |" % (
            rep, share([r for r in promise_rows if r["rep"] == rep])))
    L.append("")
    L.append("## Rule-hit frequencies (all CoS; a CoS can hit several)")
    L.append("")
    L.append("| Rule | hits |")
    L.append("|---|---|")
    for name, _ in RULES:
        n = sum(1 for r in rows if name in r["rules_hit"].split("+"))
        L.append("| %s | %d |" % (name, n))
    L.append("")
    L.append("## Spot-check sample (30 CoS, seed 260706) — hand-label in cos_spotcheck.md")
    L.append("")
    L.append("| rep | task | idx | heuristic | text |")
    L.append("|---|---|---|---|---|")
    for idx in sample_idx:
        r = rows[idx]
        L.append("| %s | %s | %s | %s | %s |" % (
            r["rep"], r["task"], r["cos_index"], r["verdict"],
            r["cos_text"].replace("|", "\\|")))
    L.append("")
    with open(os.path.join(OUT_DIR, "cos_checkability_summary.md"), "w",
              encoding="utf-8", newline="") as f:
        f.write("\n".join(L) + "\n")
    print("Wrote %d CoS rows to %s" % (len(rows), OUT_DIR))


if __name__ == "__main__":
    main()
